"use strict";

/*
|--------------------------------------------------------------------------
| Building an MCP server in the workspace (roadmap P4-09)
|--------------------------------------------------------------------------
|
| scaffold() writes a dependency-free MCP server — JSON-RPC over stdio,
| newline-delimited, the 2025-06-18 handshake — into
| <workspace>/.agent/mcp-servers/<name>/:
|
|   node     server.js (the protocol, never edited) + tools.js (the tools:
|            name, description, inputSchema, async handler(args))
|   python   server.py + tools.py (the same, with def handlers)
|
| Nothing is installed, so a server works the moment it is written and
| hot-loads into the manager (register: add() proves the connection and
| discovers its tools). fromOpenApi() turns an OpenAPI 3 JSON document
| into tools.js entries: one tool per operation, path / query / header
| parameters and a JSON body as its input schema, the call made with
| fetch against the document's first server (or base_url), a bearer
| token from OPENAPI_BEARER_TOKEN when one is set.
|--------------------------------------------------------------------------
*/

const fs = require("fs");
const path = require("path");

const NAME = /^[a-zA-Z0-9][a-zA-Z0-9_.-]{0,63}$/;
const TOOL_NAME = /^[a-zA-Z0-9_-]{1,64}$/;
/* the generated server's own environment (a separate process) is read
   with bracket access: those variables are not settings of this runtime */
const settings = require("../config");
const maxOperations = () => settings.get("MCP_OPENAPI_MAX_OPERATIONS");


function serverDir(workspaceRoot, name) {

    return path.join(workspaceRoot, ".agent", "mcp-servers", name);
}


function checkTools(tools) {

    if (!Array.isArray(tools) || tools.length === 0) {
        throw new Error("a server needs at least one tool: [{name, description, input_schema, body}]");
    }

    const seen = new Set();

    return tools.map((tool, index) => {

        if (!tool || typeof tool !== "object") throw new Error(`tool ${index + 1} must be an object`);

        const name = String(tool.name || "");

        if (!TOOL_NAME.test(name)) throw new Error(`tool ${index + 1}: "${name}" is not a usable tool name (letters, digits, _ and -)`);
        if (seen.has(name)) throw new Error(`tool "${name}" is declared twice`);

        seen.add(name);

        const schema = tool.input_schema || tool.inputSchema || { type: "object", properties: {} };

        if (!schema || typeof schema !== "object" || Array.isArray(schema)) throw new Error(`tool "${name}": input_schema must be a JSON schema object`);

        return {
            name,
            description: String(tool.description || name),
            inputSchema: schema,
            body: typeof tool.body === "string" && tool.body.trim() ? tool.body : null,
            readOnly: tool.read_only === true
        };
    });
}


/* ------------------------------------------------------------------ node */

const NODE_SERVER = `#!/usr/bin/env node
"use strict";

/*
| Generated by structured-ai (mcp_build): a dependency-free MCP server over
| stdio. The protocol lives here and is not meant to be edited; the tools
| are in tools.js. After editing tools.js, mcp_build {action: "reload"}
| restarts this server.
*/

const readline = require("readline");
const tools = require("./tools.js");

const SERVER = { name: __SERVER_NAME__, version: "0.1.0" };

function send(message) {
    process.stdout.write(JSON.stringify(message) + "\\n");
}

function text(value) {
    return typeof value === "string" ? value : JSON.stringify(value, null, 2);
}

async function handle(method, params) {
    switch (method) {
        case "initialize":
            return { protocolVersion: params.protocolVersion || "2025-06-18", capabilities: { tools: {} }, serverInfo: SERVER };
        case "ping":
            return {};
        case "tools/list":
            return {
                tools: tools.map(tool => ({
                    name: tool.name,
                    description: tool.description,
                    inputSchema: tool.inputSchema || { type: "object", properties: {} },
                    ...(tool.annotations ? { annotations: tool.annotations } : {})
                }))
            };
        case "tools/call": {
            const tool = tools.find(item => item.name === params.name);
            if (!tool) throw Object.assign(new Error("unknown tool: " + params.name), { code: -32602 });
            try {
                return { content: [{ type: "text", text: text(await tool.handler(params.arguments || {})) }] };
            } catch (error) {
                return { content: [{ type: "text", text: error && error.message ? error.message : String(error) }], isError: true };
            }
        }
        default:
            throw Object.assign(new Error("method not found: " + method), { code: -32601 });
    }
}

readline.createInterface({ input: process.stdin }).on("line", async line => {
    let message;
    try { message = JSON.parse(line); } catch { return; }
    if (!message || message.id === undefined || message.id === null || typeof message.method !== "string") return;
    try {
        send({ jsonrpc: "2.0", id: message.id, result: await handle(message.method, message.params || {}) });
    } catch (error) {
        send({ jsonrpc: "2.0", id: message.id, error: { code: Number.isInteger(error.code) ? error.code : -32603, message: error.message } });
    }
});
`;


function nodeTools(tools) {

    const entries = tools.map(tool => `    {
        name: ${JSON.stringify(tool.name)},
        description: ${JSON.stringify(tool.description)},
        inputSchema: ${JSON.stringify(tool.inputSchema, null, 4).replace(/\n/g, "\n        ")},${tool.readOnly ? "\n        annotations: { readOnlyHint: true }," : ""}
        async handler(args) {
${(tool.body || `return { echo: args, note: "edit the handler of ${tool.name} in tools.js" };`).split("\n").map(line => `            ${line}`).join("\n")}
        }
    }`);

    return `"use strict";

/* The tools of this MCP server: edit freely, then mcp_build {action: "reload"}. */

module.exports = [
${entries.join(",\n")}
];
`;
}


/* ---------------------------------------------------------------- python */

const PYTHON_SERVER = `#!/usr/bin/env python3
# Generated by structured-ai (mcp_build): a dependency-free MCP server over
# stdio. The protocol lives here; the tools are in tools.py. After editing
# tools.py, mcp_build {"action": "reload"} restarts this server.

import json
import sys

sys.path.insert(0, __import__("os").path.dirname(__import__("os").path.abspath(__file__)))

from tools import TOOLS

SERVER = {"name": __SERVER_NAME__, "version": "0.1.0"}


def text(value):
    return value if isinstance(value, str) else json.dumps(value, indent=2)


def handle(method, params):
    if method == "initialize":
        return {"protocolVersion": params.get("protocolVersion") or "2025-06-18", "capabilities": {"tools": {}}, "serverInfo": SERVER}
    if method == "ping":
        return {}
    if method == "tools/list":
        return {"tools": [{k: v for k, v in {"name": t["name"], "description": t["description"], "inputSchema": t.get("inputSchema") or {"type": "object", "properties": {}}, "annotations": t.get("annotations")}.items() if v is not None} for t in TOOLS]}
    if method == "tools/call":
        tool = next((t for t in TOOLS if t["name"] == params.get("name")), None)
        if tool is None:
            raise LookupError("unknown tool: %s" % params.get("name"))
        try:
            return {"content": [{"type": "text", "text": text(tool["handler"](params.get("arguments") or {}))}]}
        except Exception as error:  # a failing tool answers isError
            return {"content": [{"type": "text", "text": str(error)}], "isError": True}
    raise NotImplementedError("method not found: %s" % method)


for line in sys.stdin:
    try:
        message = json.loads(line)
    except ValueError:
        continue
    if not isinstance(message, dict) or message.get("id") is None or not isinstance(message.get("method"), str):
        continue
    try:
        answer = {"jsonrpc": "2.0", "id": message["id"], "result": handle(message["method"], message.get("params") or {})}
    except NotImplementedError as error:
        answer = {"jsonrpc": "2.0", "id": message["id"], "error": {"code": -32601, "message": str(error)}}
    except Exception as error:
        answer = {"jsonrpc": "2.0", "id": message["id"], "error": {"code": -32602 if isinstance(error, LookupError) else -32603, "message": str(error)}}
    sys.stdout.write(json.dumps(answer) + "\\n")
    sys.stdout.flush()
`;


function pythonTools(tools) {

    const functions = tools.map(tool => `def ${tool.name.replace(/-/g, "_")}(args):
${(tool.body || `return {"echo": args, "note": "edit ${tool.name} in tools.py"}`).split("\n").map(line => `    ${line}`).join("\n")}
`);

    const table = tools.map(tool => `    {
        "name": ${JSON.stringify(tool.name)},
        "description": ${JSON.stringify(tool.description)},
        "inputSchema": json.loads(${JSON.stringify(JSON.stringify(tool.inputSchema))}),${tool.readOnly ? "\n        \"annotations\": {\"readOnlyHint\": True}," : ""}
        "handler": ${tool.name.replace(/-/g, "_")},
    }`);

    return `# The tools of this MCP server: edit freely, then mcp_build {"action": "reload"}.

import json


${functions.join("\n\n")}

TOOLS = [
${table.join(",\n")}
]
`;
}


/* --------------------------------------------------------------- openapi */

function operationName(method, route, operation, taken) {

    let base = operation.operationId
        ? String(operation.operationId)
        : `${method}_${route.replace(/\{([^}]+)\}/g, "by_$1")}`;

    base = base.replace(/[^a-zA-Z0-9_-]+/g, "_").replace(/^_+|_+$/g, "").slice(0, 60) || method;

    let name = base;
    let counter = 2;

    while (taken.has(name)) name = `${base}_${counter++}`;

    taken.add(name);

    return name;
}


function resolveRef(document, schema, depth = 0) {

    if (!schema || typeof schema !== "object" || depth > 8) return schema || {};

    if (typeof schema.$ref === "string" && schema.$ref.startsWith("#/")) {
        const target = schema.$ref.slice(2).split("/").reduce((node, key) => node && node[key.replace(/~1/g, "/").replace(/~0/g, "~")], document);
        return resolveRef(document, target, depth + 1);
    }

    if (Array.isArray(schema)) return schema.map(item => resolveRef(document, item, depth + 1));

    const out = {};

    for (const [key, value] of Object.entries(schema)) {
        out[key] = value && typeof value === "object" ? resolveRef(document, value, depth + 1) : value;
    }

    return out;
}


function fromOpenApi(document, { baseUrl = null } = {}) {

    if (!document || typeof document !== "object" || !document.paths || typeof document.paths !== "object") {
        throw new Error("not an OpenAPI document: it has no \"paths\" object");
    }

    if (!document.openapi && !document.swagger) {
        throw new Error("not an OpenAPI document: it has neither \"openapi\" nor \"swagger\"");
    }

    const base = baseUrl || (Array.isArray(document.servers) && document.servers[0] && document.servers[0].url) || null;

    if (!base || !/^https?:\/\//.test(base)) {
        throw new Error("the API's base URL is unknown: the document has no absolute servers[0].url, so pass base_url");
    }

    const taken = new Set();
    const operations = [];

    for (const [route, item] of Object.entries(document.paths)) {

        for (const method of ["get", "post", "put", "patch", "delete"]) {

            const operation = item && item[method];

            if (!operation) continue;

            if (operations.length >= maxOperations()) break;

            const parameters = [...(item.parameters || []), ...(operation.parameters || [])].map(parameter => resolveRef(document, parameter));
            const properties = {};
            const required = [];
            const placement = {};

            for (const parameter of parameters) {
                if (!parameter || !parameter.name || !["path", "query", "header"].includes(parameter.in)) continue;
                const key = parameter.name;
                properties[key] = { ...(resolveRef(document, parameter.schema) || { type: "string" }), ...(parameter.description ? { description: parameter.description } : {}) };
                placement[key] = parameter.in;
                if (parameter.required || parameter.in === "path") required.push(key);
            }

            const body = operation.requestBody && resolveRef(document, operation.requestBody);
            const json = body && body.content && body.content["application/json"];

            if (json) {
                properties.body = { ...(resolveRef(document, json.schema) || { type: "object" }), description: "JSON request body" };
                placement.body = "body";
                if (body.required) required.push("body");
            }

            operations.push({
                name: operationName(method, route, operation, taken),
                description: String(operation.summary || operation.description || `${method.toUpperCase()} ${route}`).slice(0, 500),
                inputSchema: { type: "object", properties, ...(required.length ? { required } : {}) },
                readOnly: method === "get",
                request: { method: method.toUpperCase(), route, placement }
            });
        }
    }

    if (operations.length === 0) {
        throw new Error("the OpenAPI document has no operations (get, post, put, patch, delete)");
    }

    return { baseUrl: base, operations, title: document.info && document.info.title };
}


function openApiNodeTools(spec) {

    const table = spec.operations.map(operation => ({
        name: operation.name,
        description: operation.description,
        inputSchema: operation.inputSchema,
        ...(operation.readOnly ? { annotations: { readOnlyHint: true } } : {}),
        request: operation.request
    }));

    return `"use strict";

/*
| Generated by structured-ai (mcp_build) from an OpenAPI document${spec.title ? ` (${spec.title})` : ""}.
| One tool per operation; set OPENAPI_BEARER_TOKEN in the server's env for
| an API that needs a token. Edit freely, then mcp_build {action: "reload"}.
*/

const BASE_URL = process.env["OPENAPI_BASE_URL"] || ${JSON.stringify(spec.baseUrl)};

const OPERATIONS = ${JSON.stringify(table, null, 4)};

async function call(operation, args) {
    const { method, route, placement } = operation.request;
    let pathname = route;
    const url = new URL(BASE_URL.replace(/\\/$/, "") + "/");
    const headers = { accept: "application/json" };
    let body;
    for (const [key, where] of Object.entries(placement)) {
        if (args[key] === undefined) continue;
        if (where === "path") pathname = pathname.replace("{" + key + "}", encodeURIComponent(String(args[key])));
        if (where === "query") url.searchParams.set(key, typeof args[key] === "string" ? args[key] : JSON.stringify(args[key]));
        if (where === "header") headers[key] = String(args[key]);
        if (where === "body") { body = JSON.stringify(args[key]); headers["content-type"] = "application/json"; }
    }
    if (process.env["OPENAPI_BEARER_TOKEN"]) headers.authorization = "Bearer " + process.env["OPENAPI_BEARER_TOKEN"];
    const target = new URL(pathname.replace(/^\\//, ""), url);
    target.search = url.search;
    const response = await fetch(target, { method, headers, body });
    const text = await response.text();
    let payload = text;
    try { payload = JSON.parse(text); } catch { /* not JSON */ }
    if (!response.ok) throw new Error(method + " " + target.pathname + " answered " + response.status + ": " + (typeof payload === "string" ? payload : JSON.stringify(payload)).slice(0, 500));
    return payload;
}

module.exports = OPERATIONS.map(operation => ({
    name: operation.name,
    description: operation.description,
    inputSchema: operation.inputSchema,
    ...(operation.annotations ? { annotations: operation.annotations } : {}),
    handler: args => call(operation, args)
}));
`;
}


/* ---------------------------------------------------------------- write */

function scaffold({ workspaceRoot, name, language = "node", tools = null, openapi = null, overwrite = false }) {

    if (!NAME.test(String(name || ""))) {
        throw new Error(`"${name}" is not a usable server name; use letters, digits, dot, dash or underscore`);
    }

    if (!["node", "python"].includes(language)) {
        throw new Error("language must be node or python");
    }

    if (openapi && language !== "node") {
        throw new Error("a server generated from OpenAPI is written in node");
    }

    const dir = serverDir(workspaceRoot, name);
    const serverFile = path.join(dir, language === "node" ? "server.js" : "server.py");
    const toolsFile = path.join(dir, language === "node" ? "tools.js" : "tools.py");

    if (fs.existsSync(toolsFile) && !overwrite) {
        throw new Error(`a server called "${name}" already exists in ${path.relative(workspaceRoot, dir)}; reload it, or pass overwrite: true`);
    }

    fs.mkdirSync(dir, { recursive: true });

    const protocol = (language === "node" ? NODE_SERVER : PYTHON_SERVER).replace("__SERVER_NAME__", JSON.stringify(name));

    let toolsSource;
    let toolNames;

    if (openapi) {
        toolsSource = openApiNodeTools(openapi);
        toolNames = openapi.operations.map(operation => operation.name);
    } else {
        const checked = checkTools(tools);
        toolsSource = language === "node" ? nodeTools(checked) : pythonTools(checked);
        toolNames = checked.map(tool => tool.name);
    }

    fs.writeFileSync(serverFile, protocol, "utf8");
    fs.writeFileSync(toolsFile, toolsSource, "utf8");
    fs.writeFileSync(path.join(dir, "README.md"), `# ${name}\n\nAn MCP server built by structured-ai (mcp_build, ${language}).\n\n- protocol: \`${path.basename(serverFile)}\` (do not edit)\n- tools: \`${path.basename(toolsFile)}\`\n\nRun it by hand with \`${language === "node" ? "node server.js" : "python3 server.py"}\`; it speaks newline-delimited JSON-RPC on stdin/stdout.\n`, "utf8");

    return { dir, serverFile, toolsFile, language, tools: toolNames };
}


function definitionFor({ dir, serverFile, language, name, description }) {

    return {
        transport: "stdio",
        command: language === "node" ? process.execPath : (process.platform === "win32" ? "python" : "python3"),
        args: [serverFile],
        cwd: dir,
        description: description || `built by the agent (${language})`
    };
}


/* what an existing server in the workspace is written in */
function existing(workspaceRoot, name) {

    const dir = serverDir(workspaceRoot, name);

    if (fs.existsSync(path.join(dir, "server.js"))) return { dir, serverFile: path.join(dir, "server.js"), language: "node" };
    if (fs.existsSync(path.join(dir, "server.py"))) return { dir, serverFile: path.join(dir, "server.py"), language: "python" };

    return null;
}


module.exports = { serverDir, checkTools, nodeTools, pythonTools, fromOpenApi, openApiNodeTools, scaffold, definitionFor, existing, maxOperations };
